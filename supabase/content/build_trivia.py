"""
Verify the daily Bible questions against the Bible text, then write the seed SQL.

  python3 supabase/content/build_trivia.py KJV.json [out.sql]

KJV.json is the public-domain King James Version as JSON
(https://github.com/thiagobodruk/bible, json/en_kjv.json).
For every question it checks that:
  - the reference exists
  - the "check" words appear in that passage
  - there are exactly three wrong answers, all different from the right one
"""
import json, random, re, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from trivia_source import Q

bible = json.load(open(sys.argv[1], encoding='utf-8-sig'))
books = {b['name'].lower(): b for b in bible}
books['psalm'] = books['psalms']

def passage(ref):
    m = re.match(r'^(.+?) (\d+):(\d+)(?:-(\d+))?$', ref)
    if not m: raise ValueError(f'bad reference {ref}')
    book, ch, v1, v2 = m.group(1).lower(), int(m.group(2)), int(m.group(3)), int(m.group(4) or m.group(3))
    b = books.get(book)
    if not b: raise ValueError(f'unknown book in {ref}')
    if ch > len(b['chapters']): raise ValueError(f'no chapter {ch} in {ref}')
    verses = b['chapters'][ch - 1]
    if v2 > len(verses) or v1 < 1 or v2 < v1: raise ValueError(f'no verse range in {ref}')
    return ' '.join(verses[v1 - 1:v2])

norm = lambda s: re.sub(r'[^a-z0-9 ]', '', re.sub(r'\s+', ' ', s.lower().replace('æ', 'ae').replace('’', "'")))
problems, seen = [], set()
for i, (q, right, wrong, ref, check, explain) in enumerate(Q, 1):
    try:
        text = passage(ref)
        if norm(check) not in norm(text): problems.append(f'{i}. "{check}" not found in {ref}: {text[:160]}')
    except ValueError as e:
        problems.append(f'{i}. {e}')
    if len(wrong) != 3 or right in wrong or len(set(wrong)) != 3: problems.append(f'{i}. answers are not four different choices')
    if q in seen: problems.append(f'{i}. duplicate question')
    seen.add(q)
    for t in (q, right, explain, *wrong):
        if '—' in t or '–' in t: problems.append(f'{i}. has a dash: {t}')
if problems:
    print('\n'.join(problems)); sys.exit(1)
print(f'All {len(Q)} questions verified against the text.')

# Shuffle the choices for each question (fixed, so rebuilding gives the same result),
# and give the questions a random order.
rng = random.Random(20261116)
order = list(range(len(Q))); rng.shuffle(order)
sq = lambda s: "'" + s.replace("'", "''") + "'"
rows = []
for pos, i in enumerate(order):
    q, right, wrong, ref, check, explain = Q[i]
    choices = [right, *wrong]; rng.shuffle(choices)
    arr = 'array[' + ', '.join(sq(c) for c in choices) + ']'
    rows.append(f'({pos + 1}, {sq(q)}, {arr}, {choices.index(right)}, {sq(ref)}, {sq(explain)})')
sql = ('-- Generated by supabase/content/build_trivia.py. Every answer was checked against the Bible text.\n'
       'insert into public.trivia_questions (sort_key, question, choices, answer, reference, explanation) values\n'
       + ',\n'.join(rows) + '\non conflict (sort_key) do update set question = excluded.question, choices = excluded.choices,\n'
       '  answer = excluded.answer, reference = excluded.reference, explanation = excluded.explanation;\n')
if len(sys.argv) > 2:
    open(sys.argv[2], 'w').write(sql); print('Wrote', sys.argv[2])
